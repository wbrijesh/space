#!/usr/bin/env python3
"""Write THIRD_PARTY_NOTICES.md: the licences of everything shipped inside Space.app.

Rust: crates the app and the bundled Rust plugins link (normal and build deps, from
`cargo metadata`). TypeScript: the packages installed for the bundled TypeScript plugins
(node_modules after `bun install`), plus the Bun runtime compiled into space-ts.

Run from the repo root after `bun install`: python3 scripts/third_party_notices.py
"""

import json
import os
import subprocess

SHIPPED_CRATES = {"space-app", "space-alerts", "space-permissions", "space-session-store", "space-titles", "space-trajectory"}


def rust_crates():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--offline"]))
    workspace = set(meta["workspace_members"])
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    stack = [i for i in workspace if packages[i]["name"] in SHIPPED_CRATES]
    seen = set()
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for dep in nodes[i]["deps"]:
            if any(k["kind"] in (None, "build") for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    rows = {(packages[i]["name"], packages[i]["version"], packages[i].get("license") or "see crate") for i in seen - workspace}
    return sorted(rows)


def js_packages():
    rows = set()
    for dirpath, dirnames, filenames in os.walk("node_modules"):
        dirnames[:] = [d for d in dirnames if d != ".bin"]
        if "package.json" not in filenames:
            continue
        try:
            pkg = json.load(open(os.path.join(dirpath, "package.json")))
        except (OSError, ValueError):
            continue
        if "name" in pkg and "version" in pkg and not pkg.get("private"):
            rows.add((pkg["name"], pkg["version"], str(pkg.get("license") or "see package")))
    return sorted(rows)


def table(rows):
    lines = ["| Name | Version | Licence |", "|---|---|---|"]
    lines += [f"| {n} | {v} | {l} |" for n, v, l in rows]
    return "\n".join(lines)


def main():
    text = f"""# Third-party notices

Space is MIT-licensed (see LICENSE). Space.app also contains the software below, each under its
own licence. Generated by `scripts/third_party_notices.py`; the licence texts are in each
project's source.

## Bun runtime

The bundled TypeScript plugins run from one executable compiled with [Bun](https://bun.sh)
(MIT). Bun statically links [JavaScriptCore](https://webkit.org), which is licensed under the
GNU LGPL 2.1; the source of the JavaScriptCore Bun uses is at https://github.com/oven-sh/WebKit.

## TypeScript packages

Installed for the bundled TypeScript plugins (pi-agent: the pi SDK, the Claude CLI provider, the
Agent Client Protocol SDK and their dependencies). Only the code a plugin uses is compiled in.

{table(js_packages())}

## Rust crates

Linked into the app and the bundled Rust plugins. MPL-2.0 crates are used unmodified; their
source is on crates.io.

{table(rust_crates())}
"""
    open("THIRD_PARTY_NOTICES.md", "w").write(text)
    print("wrote THIRD_PARTY_NOTICES.md")


if __name__ == "__main__":
    main()
